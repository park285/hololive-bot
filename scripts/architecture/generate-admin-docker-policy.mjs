import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const check = process.argv[2] === "--check";
assert(process.argv.length === 2 || check && process.argv.length === 3, "usage: generate-admin-docker-policy.mjs [--check]");
const policy = JSON.parse(await fs.readFile(path.join(root, "admin-dashboard/backend/internal/contract/docker-policy.json"), "utf8"));
assert.equal(policy.schemaVersion, 1);
assert.deepEqual(Object.keys(policy).sort(), ["containers", "schemaVersion"]);
const names = new Set();
const bits = { start: 1, stop: 2, restart: 4 };
for (const entry of policy.containers) {
  assert.deepEqual(Object.keys(entry).sort(), ["actions", "name"]);
  assert.match(entry.name, /^[a-z][a-z0-9-]+$/);
  assert(!names.has(entry.name), "duplicate container"); names.add(entry.name);
  assert(entry.actions.length > 0 && new Set(entry.actions).size === entry.actions.length);
  assert(entry.actions.every(action => Object.hasOwn(bits, action)), "unknown action");
}
const hash = createHash("sha256").update(JSON.stringify(policy)).digest("hex");
const rows = policy.containers.map(entry => `\t${JSON.stringify(entry.name)}: ${entry.actions.reduce((value, action) => value | bits[action], 0)},`).join("\n");
const goFile = path.join(root, "admin-dashboard/backend/internal/adapters/docker/policy_generated.go");
const goSource = execFileSync("gofmt", [], { input: `// Code generated by scripts/architecture/generate-admin-docker-policy.mjs; DO NOT EDIT.\npackage docker\n\n// PolicyHash는 앱과 전용 proxy가 공유하는 허용 정책의 SHA-256입니다.\nconst PolicyHash = "${hash}"\n\nvar containerActions = map[string]uint8{\n${rows}\n}\n`, encoding: "utf8" });
const posts = policy.containers.map(entry => `${entry.name}/(${entry.actions.join("|")})`).join("|");
// socket-proxy 1.12.3은 r.URL.Path만 검사합니다. query 제한을 이 정규식의 보장으로 표시하지 않습니다.
const compose = { services: { "admin-docker-proxy": {
  labels: { "io.hololive.admin.policy-sha256": hash },
  command: ["-loglevel=info", "-listenip=0.0.0.0", "-proxyport=2375", "-allowfrom=0.0.0.0/0",
    "-allowGET=(/v1\\.[0-9]+)?/(_ping|version|containers/json)",
    "-allowHEAD=(/v1\\.[0-9]+)?/_ping",
    `-allowPOST=(/v1\\.[0-9]+)?/containers/(${posts})`,
  ],
} } };
const outputs = new Map([[goFile, goSource], [path.join(root, "deploy/compose/admin-docker-policy.generated.json"), `${JSON.stringify(compose, null, 2)}\n`]]);
for (const [file, content] of outputs) {
  if (check) assert.equal(await fs.readFile(file, "utf8"), content, `stale policy: ${path.relative(root, file)}`);
  else await fs.writeFile(file, content);
}
console.log(`${check ? "Verified" : "Generated"} exact Docker policy for ${names.size} containers: ${hash}`);
